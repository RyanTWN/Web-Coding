function startSpeedQuiz() {
  const pool = seededShuffle([...TF_FACTS], `${Date.now()}-${currentUser?.seatNo || 1}`);
  speedState = {
    active: true,
    timeLeft: 60,
    timerId: null,
    pool,
    currentIndex: 0,
    score: 0,
    streak: 0,
    maxStreak: 0,
    totalAnswered: 0,
    history: []
  };

  showView('view-speed-quiz');
  renderSpeedQuestion();

  const startTime = Date.now();
  const totalDuration = 60 * 1000;

  speedState.timerId = setInterval(() => {
    const elapsed = Date.now() - startTime;
    const remainingMs = Math.max(0, totalDuration - elapsed);
    const seconds = Math.ceil(remainingMs / 1000);
    speedState.timeLeft = seconds;

    const textEl = document.getElementById('speed-timer-text');
    const barEl = document.getElementById('speed-timer-bar');
    if (textEl) textEl.textContent = `${seconds}s`;
    if (barEl) {
      const pct = (remainingMs / totalDuration) * 100;
      barEl.style.width = `${pct}%`;
      if (pct < 20) {
        barEl.className = 'h-full bg-rose-500 w-full transition-all';
        if (textEl) textEl.className = 'text-2xl sm:text-3xl font-black text-rose-600 font-mono animate-pulse';
      } else if (pct < 50) {
        barEl.className = 'h-full bg-amber-500 w-full transition-all';
        if (textEl) textEl.className = 'text-2xl sm:text-3xl font-black text-amber-600 font-mono';
      } else {
        barEl.className = 'h-full bg-gradient-to-r from-emerald-400 to-amber-400 w-full transition-all';
        if (textEl) textEl.className = 'text-2xl sm:text-3xl font-black text-orange-600 font-mono';
      }
    }

    if (remainingMs <= 0) {
      clearInterval(speedState.timerId);
      finishSpeedQuiz();
    }
  }, 100);
}

function renderSpeedQuestion() {
  if (speedState.currentIndex >= speedState.pool.length) {
    speedState.pool = seededShuffle([...TF_FACTS], `cycle-${Date.now()}`);
    speedState.currentIndex = 0;
  }
  const q = speedState.pool[speedState.currentIndex];
  document.getElementById('speed-question-text').textContent = q.prompt;
  document.getElementById('speed-current-score').textContent = speedState.score;

  const streakTag = document.getElementById('speed-streak-tag');
  const streakNum = document.getElementById('speed-streak-num');
  if (speedState.streak >= 2) {
    streakTag.classList.remove('hidden');
    streakNum.textContent = speedState.streak;
  } else {
    streakTag.classList.add('hidden');
  }
}

function answerSpeed(userChoice) {
  if (!speedState.active) return;
  const q = speedState.pool[speedState.currentIndex];
  const isCorrect = Boolean(userChoice) === Boolean(q.isTrue);

  speedState.totalAnswered++;
  if (isCorrect) {
    speedState.score++;
    speedState.streak++;
    speedState.maxStreak = Math.max(speedState.maxStreak, speedState.streak);
  } else {
    speedState.streak = 0;
  }

  speedState.history.push({
    prompt: q.prompt,
    userChoice: Boolean(userChoice),
    isTrue: q.isTrue,
    isCorrect,
    explanation: q.explanation
  });

  speedState.currentIndex++;
  renderSpeedQuestion();
}

function finishSpeedQuiz() {
  speedState.active = false;
  if (speedState.timerId) clearInterval(speedState.timerId);

  const prevBest = Number(localStorage.getItem('cool_learning_social_speed_best') || 0);
  let isNewRecord = false;
  if (speedState.score > prevBest) {
    localStorage.setItem('cool_learning_social_speed_best', String(speedState.score));
    isNewRecord = true;
  }

  document.getElementById('speed-res-correct').textContent = speedState.score;
  document.getElementById('speed-res-streak').textContent = speedState.maxStreak;
  document.getElementById('speed-res-total').textContent = speedState.totalAnswered;

  const recordEl = document.getElementById('speed-new-record');
  if (recordEl) recordEl.classList.toggle('hidden', !isNewRecord);

  const wrongs = speedState.history.filter(item => !item.isCorrect);
  const listEl = document.getElementById('speed-wrong-list');
  const wrongCountTag = document.getElementById('speed-wrong-count-tag');

  if (wrongs.length === 0) {
    wrongCountTag.textContent = '全對！太神了';
    listEl.innerHTML = '<div class="text-center py-6 text-emerald-600 font-bold text-sm"><i class="fa-solid fa-star text-2xl mb-1 block"></i>太厲害了！本輪作答完全沒有落入任何迷思陷阱！</div>';
  } else {
    wrongCountTag.textContent = `${wrongs.length} 題`;
    listEl.innerHTML = wrongs.map(item => `
      <div class="bg-rose-50 border border-rose-100 rounded-2xl p-3.5 text-xs text-rose-900 leading-relaxed">
        <div class="flex items-start gap-2 font-bold mb-1">
          <span class="px-1.5 py-0.5 rounded bg-rose-200 text-rose-700 text-[10px]">你的答案: ${item.userChoice ? '⭕ 正確' : '❌ 錯誤'}</span>
          <span class="px-1.5 py-0.5 rounded bg-emerald-200 text-emerald-800 text-[10px]">正確解答: ${item.isTrue ? '⭕ 正確' : '❌ 錯誤'}</span>
        </div>
        <p class="font-bold text-slate-800 mb-1">${item.prompt}</p>
        <p class="text-rose-700 font-medium">${item.explanation}</p>
      </div>
    `).join('');
  }

  renderSpeedBestScore();
  showView('view-speed-result');
}

function exitSpeedQuiz() {
  speedState.active = false;
  if (speedState.timerId) clearInterval(speedState.timerId);
  showView('view-setup');
}

function renderCalendar() {
  const year = calendarDate.getFullYear();
  const month = calendarDate.getMonth();
  const calTitle = document.getElementById('cal-title');
  if (calTitle) calTitle.textContent = `${year} 年 ${month + 1} 月`;
  const totals = getCalendarTotals(history, year, month);
  const completionCount = document.getElementById('completion-count');
  if (completionCount) completionCount.textContent = `${totals.totalQuestions} 題・${totals.totalScore} 分`;
  const grid = document.getElementById('calendar-grid');
  if (!grid) return;
  grid.innerHTML = '';
  const firstDay = new Date(year, month, 1).getDay();
  const daysInMonth = new Date(year, month + 1, 0).getDate();
  for (let index = 0; index < firstDay; index++) grid.appendChild(document.createElement('div'));
  for (let day = 1; day <= daysInMonth; day++) {
    const dateStr = `${year}-${String(month + 1).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
    const record = history.find(item => item.date === dateStr);
    const cell = document.createElement('button');
    cell.className = `h-10 rounded-xl flex flex-col items-center justify-center font-bold text-xs transition ${record?.completedAttempts ? 'bg-orange-100 text-orange-800 border border-orange-300' : 'bg-slate-50 text-slate-400'}`;
    cell.innerHTML = `<span>${day}</span>${record?.completedAttempts ? `<span class="w-1.5 h-1.5 rounded-full bg-orange-500 mt-0.5"></span>` : ''}`;
    cell.onclick = () => {
      const detailEl = document.getElementById('calendar-detail');
      if (detailEl) {
        detailEl.textContent = record
          ? `${dateStr}：完成 ${record.completedAttempts} 次，共 ${record.totalQuestions} 題，得分 ${record.totalScore} 分`
          : `${dateStr}：當日尚無完成紀錄`;
      }
    };
    grid.appendChild(cell);
  }
}

function startReview() {
  reviewQuestions = [...wrongBank];
  if (!reviewQuestions.length) return showToast('目前沒有待複習錯題', 'emerald');
  reviewIndex = 0;
  showView('view-review');
  renderReviewQuestion();
}

function renderReviewQuestion() {
  const item = reviewQuestions[reviewIndex];
  const emptyEl = document.getElementById('review-empty');
  const contentEl = document.getElementById('review-content');
  if (!item) {
    if (emptyEl) emptyEl.classList.remove('hidden');
    if (contentEl) contentEl.classList.add('hidden');
    return;
  }
  if (emptyEl) emptyEl.classList.add('hidden');
  if (contentEl) contentEl.classList.remove('hidden');
  document.getElementById('review-meta').textContent = `${reviewIndex + 1} / ${reviewQuestions.length}`;
  document.getElementById('review-badge').textContent = `${item.publisher || ''}・${item.chapter || ''}`;
  document.getElementById('review-question').textContent = item.question;
  const list = document.getElementById('review-answers');
  list.innerHTML = '';
  item.options.forEach((option, index) => {
    const button = document.createElement('button');
    button.className = 'w-full p-4 rounded-2xl border-2 border-slate-200 bg-white hover:border-orange-300 text-left font-bold transition';
    button.innerHTML = `<span class="inline-flex w-7 h-7 mr-2 rounded-lg bg-slate-100 items-center justify-center text-xs font-black">${String.fromCharCode(65 + index)}</span>${option}`;
    button.onclick = () => answerReviewQuestion(option, button);
    list.appendChild(button);
  });
  document.getElementById('review-feedback').classList.add('hidden');
  document.getElementById('review-next').classList.add('hidden');
}

async function answerReviewQuestion(option, selectedButton) {
  const item = reviewQuestions[reviewIndex];
  const correct = option === item.answer;
  document.querySelectorAll('#review-answers button').forEach(button => {
    button.disabled = true;
    if (button.textContent.slice(1).trim() === item.answer) button.classList.add('is-correct');
  });
  if (!correct) selectedButton.classList.add('is-wrong');
  if (correct) {
    await socialFetch('/social-review', {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ seatNo: currentUser.seatNo, questionId: item.id })
    }).catch(() => null);
    wrongBank = wrongBank.filter(q => q.id !== item.id);
    const wrongCountEl = document.getElementById('wrong-count');
    if (wrongCountEl) wrongCountEl.textContent = wrongBank.length;
  }
  const feedback = document.getElementById('review-feedback');
  feedback.className = `mt-5 rounded-2xl p-4 text-sm leading-relaxed ${correct ? 'bg-emerald-50 text-emerald-800' : 'bg-rose-50 text-rose-800'}`;
  feedback.innerHTML = `<strong>${correct ? '答對了！已移出錯題清單' : `正確答案：${item.answer}`}</strong><br>${item.explanation}`;
  document.getElementById('review-next').classList.remove('hidden');
}

function advanceReview() {
  reviewIndex++;
  if (reviewIndex >= reviewQuestions.length) {
    showToast('錯題複習完成！', 'emerald');
    showView('view-setup');
  } else {
    renderReviewQuestion();
  }
}

