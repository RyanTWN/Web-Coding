function buildDailyQuestions(publisher, chapterTitle, attemptNo = 1) {
  const chapter = findChapter(publisher, chapterTitle);
  const publisherSlug = { '康軒': 'knsh', '南一': 'nani', '翰林': 'hanlin' }[publisher] || 'soc';
  const chapterNo = (CURRICULUM[publisher] || []).findIndex(item => item[0] === chapterTitle) + 1 || 1;
  const primaryTopics = chapter?.[1] || ['governance', 'economics'];
  const allKnownTopics = Object.keys(FACTS);

  const seedPrefix = `${currentUser?.seatNo || 1}-${todayKey}-${attemptNo}-${publisherSlug}-${chapterNo}`;
  const seenPrompts = new Set();
  const selectedQuestions = [];

  // 1. 核心基礎 12 題
  let corePool = primaryTopics.flatMap(topic =>
    (FACTS[topic] || []).map((fact, index) => {
      const [prompt, correct, ...rest] = fact;
      const explanation = rest.pop();
      return {
        id: `soc-${publisherSlug}-${chapterNo}-core-${topic}-${index + 1}`,
        kind: '核心基礎',
        type: 'choice',
        question: prompt,
        rawOptions: [correct, ...rest],
        answer: correct,
        explanation
      };
    })
  );
  if (corePool.length < 12) {
    const fallbackCore = allKnownTopics.flatMap(topic =>
      (FACTS[topic] || []).map((fact, index) => {
        const [prompt, correct, ...rest] = fact;
        const explanation = rest.pop();
        return {
          id: `soc-${publisherSlug}-${chapterNo}-core-${topic}-${index + 1}`,
          kind: '核心基礎',
          type: 'choice',
          question: prompt,
          rawOptions: [correct, ...rest],
          answer: correct,
          explanation
        };
      })
    );
    corePool = [...corePool, ...fallbackCore];
  }
  const shuffledCore = seededShuffle(corePool, `${seedPrefix}-core`);
  for (const item of shuffledCore) {
    if (selectedQuestions.length >= 12) break;
    if (!seenPrompts.has(item.question)) {
      seenPrompts.add(item.question);
      selectedQuestions.push({
        ...item,
        options: seededShuffle(item.rawOptions, `${seedPrefix}-${item.id}`)
      });
    }
  }

  // 2. 統整加深 6 題
  let integPool = primaryTopics.flatMap(topic =>
    (INTEGRATION_FACTS[topic] || []).map((item, index) => ({
      id: `soc-${publisherSlug}-${chapterNo}-integ-${topic}-${index + 1}`,
      kind: '統整加深',
      type: item.type || 'cloze',
      question: item.prompt,
      rawOptions: [item.answer, ...item.distractors],
      answer: item.answer,
      explanation: item.explanation
    }))
  );
  if (integPool.length < 6) {
    const fallbackInteg = allKnownTopics.flatMap(topic =>
      (INTEGRATION_FACTS[topic] || []).map((item, index) => ({
        id: `soc-${publisherSlug}-${chapterNo}-integ-${topic}-${index + 1}`,
        kind: '統整加深',
        type: item.type || 'cloze',
        question: item.prompt,
        rawOptions: [item.answer, ...item.distractors],
        answer: item.answer,
        explanation: item.explanation
      }))
    );
    integPool = [...integPool, ...fallbackInteg];
  }
  const shuffledInteg = seededShuffle(integPool, `${seedPrefix}-integ`);
  let integCount = 0;
  for (const item of shuffledInteg) {
    if (integCount >= 6) break;
    if (!seenPrompts.has(item.question)) {
      seenPrompts.add(item.question);
      selectedQuestions.push({
        ...item,
        options: seededShuffle(item.rawOptions, `${seedPrefix}-${item.id}`)
      });
      integCount++;
    }
  }

  // 3. 素養挑戰 2 題
  let compPool = primaryTopics.flatMap(topic =>
    (COMPETENCY_FACTS[topic] || []).map((item, index) => ({
      id: `soc-${publisherSlug}-${chapterNo}-comp-${topic}-${index + 1}`,
      kind: '素養挑戰',
      type: item.type || 'sequence',
      question: item.prompt,
      rawOptions: [item.answer, ...item.distractors],
      answer: item.answer,
      explanation: item.explanation
    }))
  );
  if (compPool.length < 2) {
    const fallbackComp = allKnownTopics.flatMap(topic =>
      (COMPETENCY_FACTS[topic] || []).map((item, index) => ({
        id: `soc-${publisherSlug}-${chapterNo}-comp-${topic}-${index + 1}`,
        kind: '素養挑戰',
        type: item.type || 'sequence',
        question: item.prompt,
        rawOptions: [item.answer, ...item.distractors],
        answer: item.answer,
        explanation: item.explanation
      }))
    );
    compPool = [...compPool, ...fallbackComp];
  }
  const shuffledComp = seededShuffle(compPool, `${seedPrefix}-comp`);
  let compCount = 0;
  for (const item of shuffledComp) {
    if (compCount >= 2) break;
    if (!seenPrompts.has(item.question)) {
      seenPrompts.add(item.question);
      selectedQuestions.push({
        ...item,
        options: seededShuffle(item.rawOptions, `${seedPrefix}-${item.id}`)
      });
      compCount++;
    }
  }

  return selectedQuestions.slice(0, DAILY_TOTAL);
}

function getCalendarTotals(records, year, month) {
  const prefix = `${year}-${String(month + 1).padStart(2, '0')}-`;
  return records.filter(item => item.date.startsWith(prefix)).reduce((total, item) => ({
    completedAttempts: total.completedAttempts + Number(item.completedAttempts || 0),
    totalQuestions: total.totalQuestions + Number(item.totalQuestions || 0),
    totalScore: total.totalScore + Number(item.totalScore || 0)
  }), { completedAttempts: 0, totalQuestions: 0, totalScore: 0 });
}

function showToast(message, tone = 'slate') {
  const toast = document.getElementById('toast');
  if (!toast) return;
  document.getElementById('toast-text').textContent = message;
  document.getElementById('toast-bg').className = `${tone === 'rose' ? 'bg-rose-600' : tone === 'emerald' ? 'bg-emerald-600' : 'bg-slate-800'} text-white px-5 py-3 rounded-2xl shadow-xl flex items-center gap-2 font-bold text-sm`;
  toast.classList.remove('-translate-y-16', 'opacity-0', 'pointer-events-none');
  setTimeout(() => toast.classList.add('-translate-y-16', 'opacity-0', 'pointer-events-none'), 2200);
}

function showView(id) {
  ['view-setup', 'view-quiz', 'view-result', 'view-review', 'view-speed-quiz', 'view-speed-result'].forEach(view => {
    const el = document.getElementById(view);
    if (el) el.classList.toggle('hidden', view !== id);
  });
}

function renderPublisherButtons() {
  const container = document.getElementById('publisher-list');
  if (!container) return;
  container.innerHTML = '';
  ALLOWED_PUBLISHERS.forEach(publisher => {
    const button = document.createElement('button');
    const active = publisher === selectedPublisher;
    button.className = `py-3 rounded-2xl border-2 font-black transition ${active ? 'border-orange-400 bg-orange-50 text-orange-700 shadow-sm' : 'border-slate-200 bg-slate-50 text-slate-500'}`;
    button.textContent = publisher;
    button.disabled = Boolean(dailyState);
    button.onclick = () => { selectedPublisher = publisher; renderPublisherButtons(); renderChapterOptions(); };
    container.appendChild(button);
  });
}

function renderChapterOptions(preferred) {
  const select = document.getElementById('chapter-select');
  if (!select) return;
  select.innerHTML = '';
  (CURRICULUM[selectedPublisher] || []).forEach(([title]) => select.add(new Option(title, title)));
  if (preferred && findChapter(selectedPublisher, preferred)) select.value = preferred;
  select.disabled = Boolean(dailyState);
  updateChapterSummary();
}

function updateChapterSummary() {
  const select = document.getElementById('chapter-select');
  const summaryEl = document.getElementById('chapter-summary');
  if (!select || !summaryEl) return;
  const chapter = findChapter(selectedPublisher, select.value);
  summaryEl.innerHTML = `<strong>${selectedPublisher}版課程重點：</strong>${chapter?.[2] || ''}<br><span class="text-orange-700/70">題型架構：核心基礎 12 題 ＋ 統整加深 6 題 ＋ 素養挑戰 2 題（同輪去重）</span>`;
}

async function loadProgress() {
  const response = await socialFetch(`/social-progress?seatNo=${encodeURIComponent(currentUser.seatNo)}&date=${todayKey}`);
  if (response.status === 401) return logout();
  const result = await response.json();
  if (!response.ok || !result.success) throw new Error(result.error || '無法載入社會人文進度');
  dailyState = result.data;
  history = result.history || [];
  todaySummary = result.todaySummary || todaySummary;
  wrongBank = result.wrongQuestions || [];
  const wrongCountEl = document.getElementById('wrong-count');
  if (wrongCountEl) wrongCountEl.textContent = wrongBank.length;
  if (dailyState) {
    if (!dailyState.completed && dailyState.answers.length > dailyState.currentIndex) {
      dailyState.currentIndex = Math.min(DAILY_TOTAL, dailyState.answers.length);
    }
    selectedPublisher = dailyState.publisher;
    renderPublisherButtons();
    renderChapterOptions(dailyState.chapter);
    const btnStart = document.getElementById('btn-start');
    if (btnStart) btnStart.innerHTML = `繼續第 ${dailyState.attemptNo} 次測驗（${dailyState.currentIndex + 1} / ${DAILY_TOTAL}） <i class="fa-solid fa-arrow-right ml-1"></i>`;
  } else {
    renderPublisherButtons();
    renderChapterOptions();
    renderStartButton();
  }
  renderCalendar();
  renderSpeedBestScore();
}

