function getCorrectCount(state = dailyState) {
  return (state?.answers || []).filter(answer => answer.correct).length;
}

function renderQuestion() {
  const question = dailyState.questions[dailyState.currentIndex];
  if (!question) return finishQuiz();
  document.getElementById('quiz-badge').textContent = `${dailyState.publisher}・${dailyState.chapter}`;
  document.getElementById('quiz-progress').textContent = `第 ${dailyState.currentIndex + 1} / ${DAILY_TOTAL} 題`;
  document.getElementById('quiz-bar').style.width = `${(dailyState.currentIndex + 1) / DAILY_TOTAL * 100}%`;

  const kindEl = document.getElementById('question-kind');
  kindEl.textContent = question.kind || '核心基礎';
  if (question.kind === '素養挑戰') {
    kindEl.className = 'inline-block px-2.5 py-0.5 rounded-full text-xs font-black bg-purple-100 text-purple-700 tracking-wider mb-2';
  } else if (question.kind === '統整加深') {
    kindEl.className = 'inline-block px-2.5 py-0.5 rounded-full text-xs font-black bg-amber-100 text-amber-800 tracking-wider mb-2';
  } else {
    kindEl.className = 'inline-block px-2.5 py-0.5 rounded-full text-xs font-black bg-emerald-100 text-emerald-800 tracking-wider mb-2';
  }

  document.getElementById('question-text').textContent = question.question;
  const list = document.getElementById('answer-list');
  list.innerHTML = '';
  question.options.forEach((option, index) => {
    const button = document.createElement('button');
    button.className = 'answer-option w-full p-4 rounded-2xl border-2 border-slate-200 bg-white hover:border-orange-300 text-left font-bold transition';
    button.innerHTML = `<span class="inline-flex w-7 h-7 mr-2 rounded-lg bg-slate-100 items-center justify-center text-xs font-black">${String.fromCharCode(65 + index)}</span>${option}`;
    button.onclick = () => answerDailyQuestion(option, button);
    list.appendChild(button);
  });
  document.getElementById('feedback').classList.add('hidden');
  document.getElementById('btn-next').classList.add('hidden');
}

async function answerDailyQuestion(option, selectedButton) {
  const question = dailyState.questions[dailyState.currentIndex];
  const correct = option === question.answer;
  document.querySelectorAll('#answer-list .answer-option').forEach(button => {
    button.disabled = true;
    const text = button.textContent.slice(1).trim();
    if (text === question.answer) button.classList.add('is-correct');
  });
  if (!correct) selectedButton.classList.add('is-wrong');
  dailyState.answers.push({ questionId: question.id, selected: option, correct });
  if (!correct && !dailyState.wrongQuestions.some(item => item.id === question.id)) {
    dailyState.wrongQuestions.push({ ...question, publisher: dailyState.publisher, chapter: dailyState.chapter });
  }
  const feedback = document.getElementById('feedback');
  feedback.className = `mt-5 rounded-2xl p-4 text-sm leading-relaxed ${correct ? 'bg-emerald-50 text-emerald-800' : 'bg-rose-50 text-rose-800'}`;
  feedback.innerHTML = `<strong>${correct ? '答對了！' : `正確答案：${question.answer}`}</strong><br>${question.explanation}`;
  document.getElementById('btn-next').classList.remove('hidden');
  await syncState(false);
}

async function advanceQuestion() {
  dailyState.currentIndex += 1;
  if (dailyState.currentIndex >= DAILY_TOTAL) return finishQuiz();
  await syncState(false);
  renderQuestion();
}

async function finishQuiz() {
  dailyState.completed = true;
  dailyState.currentIndex = DAILY_TOTAL;
  dailyState.score = Math.round(getCorrectCount() / DAILY_TOTAL * 100);
  const result = await syncState(true);
  todaySummary = result.todaySummary || todaySummary;
  history = [{ date: todayKey, ...todaySummary }, ...history.filter(item => item.date !== todayKey)];
  wrongBank = [...new Map([...wrongBank, ...dailyState.wrongQuestions].map(item => [item.id, item])).values()];
  const wrongCountEl = document.getElementById('wrong-count');
  if (wrongCountEl) wrongCountEl.textContent = wrongBank.length;
  renderResult();
  renderCalendar();
}

function renderResult() {
  document.getElementById('result-attempt').textContent = `第 ${dailyState.attemptNo} 次測驗（12基礎＋6加深＋2素養）`;
  document.getElementById('result-correct').textContent = `${getCorrectCount()} / ${DAILY_TOTAL}`;
  document.getElementById('result-score').textContent = `${dailyState.score} 分`;
  document.getElementById('result-today-total').textContent = `今日累計：${todaySummary.completedAttempts} 次・${todaySummary.totalQuestions} 題・${todaySummary.totalScore} 分`;
  showView('view-result');
}

async function syncState(completed) {
  const response = await socialFetch('/social-progress', {
    method: 'POST', headers: { 'Content-Type': 'application/json' }, keepalive: completed,
    body: JSON.stringify({
      seatNo: currentUser.seatNo, date: todayKey, attemptNo: dailyState.attemptNo,
      publisher: dailyState.publisher, chapter: dailyState.chapter,
      questions: dailyState.questions, currentIndex: dailyState.currentIndex, answers: dailyState.answers,
      wrongQuestions: dailyState.wrongQuestions, completed, score: dailyState.score || 0
    })
  });
  const result = await response.json().catch(() => ({}));
  if (!response.ok || !result.success) throw new Error(result.error || `社會人文進度同步失敗（HTTP ${response.status}）`);
  if (result.attemptNo) dailyState.attemptNo = Number(result.attemptNo);
  return result;
}

async function startOrResume() {
  if (dailyState?.completed) return renderResult();
  if (!dailyState) {
    const chapter = document.getElementById('chapter-select').value;
    const attemptNo = Number(todaySummary.nextAttemptNo || 1);
    dailyState = {
      date: todayKey, attemptNo, publisher: selectedPublisher, chapter,
      questions: buildDailyQuestions(selectedPublisher, chapter, attemptNo),
      currentIndex: 0, answers: [], wrongQuestions: [], completed: false, score: 0
    };
    await syncState(false);
  }
  showView('view-quiz');
  renderQuestion();
}

